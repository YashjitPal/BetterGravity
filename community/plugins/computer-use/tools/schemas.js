/**
 * Zod Schemas & Lightweight Standalone Validator for Codex Computer Use Tools (Windows Version)
 * Extracted from app-initial / module 1094 & main-g2764IDy.js
 */

let z;
try {
  const zodModule = await import("zod");
  z = zodModule.z;
} catch {
  // Built-in lightweight Zod-compatible fallback for zero-dependency execution
  class Schema {
    constructor(validator) {
      this._validator = validator;
      this._description = "";
    }
    describe(d) {
      this._description = d;
      return this;
    }
    optional() {
      return new Schema((val) => (val === undefined ? { success: true, data: undefined } : this._validator(val)));
    }
    catch(fallback) {
      return new Schema((val) => {
        const res = this._validator(val);
        return res.success ? res : { success: true, data: fallback };
      });
    }
    default(fallback) {
      return new Schema((val) => (val === undefined ? { success: true, data: fallback } : this._validator(val)));
    }
    transform(fn) {
      return new Schema((val) => {
        const res = this._validator(val);
        return res.success ? { success: true, data: fn(res.data) } : res;
      });
    }
    pipe(next) {
      return new Schema((val) => {
        const res = this._validator(val);
        return res.success ? next.safeParse(res.data) : res;
      });
    }
    passthrough() { return this; }
    min() { return this; }
    max() { return this; }
    positive() { return this; }
    int() { return this; }
    nonnegative() { return this; }
    safeParse(val) {
      return this._validator(val);
    }
    parse(val) {
      const res = this.safeParse(val);
      if (!res.success) throw new Error(res.error?.message || "Validation error");
      return res.data;
    }
  }

  z = {
    string: () => new Schema((v) => typeof v === "string" ? { success: true, data: v } : { success: false, error: { message: "Expected string" } }),
    number: () => new Schema((v) => typeof v === "number" && !isNaN(v) ? { success: true, data: v } : { success: false, error: { message: "Expected number" } }),
    boolean: () => new Schema((v) => typeof v === "boolean" ? { success: true, data: v } : { success: false, error: { message: "Expected boolean" } }),
    any: () => new Schema((v) => ({ success: true, data: v })),
    enum: (values) => new Schema((v) => values.includes(v) ? { success: true, data: v } : { success: false, error: { message: `Expected one of ${values.join(", ")}` } }),
    tuple: (schemas) => new Schema((v) => {
      if (!Array.isArray(v) || v.length !== schemas.length) return { success: false, error: { message: "Tuple length mismatch" } };
      const data = [];
      for (let i = 0; i < schemas.length; i++) {
        const res = schemas[i].safeParse(v[i]);
        if (!res.success) return res;
        data.push(res.data);
      }
      return { success: true, data };
    }),
    union: (schemas) => new Schema((v) => {
      for (const s of schemas) {
        const res = s.safeParse(v);
        if (res.success) return res;
      }
      return { success: false, error: { message: "Union validation failed" } };
    }),
    object: (shape) => new Schema((v) => {
      if (typeof v !== "object" || v === null) return { success: false, error: { message: "Expected object" } };
      const data = { ...v };
      for (const key of Object.keys(shape)) {
        const res = shape[key].safeParse(v[key]);
        if (!res.success) return res;
        data[key] = res.data;
      }
      return { success: true, data };
    }),
  };
}

/**
 * Windows application identifier validator (WGn from module 1094)
 * Validates .exe filenames/paths, process: prefixes, UWP AUMID packages, and AutoGenerated classes
 */
export function isWindowsAppIdentifier(id) {
  if (typeof id !== "string") return false;
  const t = id.trim();
  return (
    /^[a-z][A-Za-z0-9-]*(?:\.[A-Za-z0-9-]+)+$/.test(t) || // Bundle identifier
    /^process:/i.test(t) ||                                // process:notepad.exe
    /(^|[\\/])[^\\/]+\.exe$/i.test(t) ||                   // C:\Windows\notepad.exe
    /[A-Za-z0-9][A-Za-z0-9.-]*_[A-Za-z0-9]+![A-Za-z0-9.-]+/.test(t) || // UWP / AUMID
    /(^|[.}])[^\\/!.}]+\.exe(?:\.|$)/i.test(t) ||
    /^Microsoft\.AutoGenerated\.\{[0-9A-F-]+\}$/i.test(t)  // Auto-generated window class
  );
}

// Clean and normalize strings
const cleanString = z
  .string()
  .transform((val) => val.replace(/\s+/g, " ").trim())
  .pipe(z.string().min(1).max(120));

const optionalCleanString = cleanString.optional().catch(undefined);

const MAX_DETAIL_LENGTH = 48;
const detailString = z
  .string()
  .transform((val) => {
    const trimmed = val.replace(/\s+/g, " ").trim();
    return trimmed.length <= MAX_DETAIL_LENGTH ? trimmed : `${trimmed.slice(0, MAX_DETAIL_LENGTH).trimEnd()}…`;
  })
  .pipe(z.string().min(1))
  .optional()
  .catch(undefined);

const textInputString = z
  .string()
  .min(1)
  .catch(undefined);

export const DirectionSchema = z
  .string()
  .transform((val) => val.trim().toLowerCase())
  .pipe(z.enum(["up", "down", "left", "right"]))
  .optional()
  .catch(undefined);

export const MouseButtonSchema = z
  .enum(["left", "right", "middle", "l", "r", "m"])
  .default("left");

export const PointSchema = z.tuple([z.number(), z.number()]);

export const ActionTargetSchema = z.union([
  z.number().int().nonnegative(),
  PointSchema,
]);

export const AppDescriptorSchema = z
  .object({
    appName: optionalCleanString,
    app_name: optionalCleanString,
    bundleId: optionalCleanString,
    bundle_id: optionalCleanString,
    bundleIdentifier: optionalCleanString,
    bundle_identifier: optionalCleanString,
    displayName: optionalCleanString,
    display_name: optionalCleanString,
    name: optionalCleanString,
    title: optionalCleanString,
  })
  .passthrough();

export const AppTargetSchema = z
  .union([cleanString, AppDescriptorSchema])
  .optional()
  .catch(undefined);

